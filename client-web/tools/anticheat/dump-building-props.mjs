// The building tables the Inferno-only game itself uses, for the server's cheat detection
// (server/src/services/anticheat/): read from the running game, after its own Inferno tuning (GLOBAL.ioTuneProps,
// the outposts' table), so they are exactly what a fair game plays by. Writes
// server/src/game-data/anticheat/buildingProps.json. Run again whenever the building tables change:
//   EMAIL=... PASSWORD=... node tools/anticheat/dump-building-props.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || "playwright");
const server = process.env.SERVER || "http://localhost:3001/";
const out = process.env.OUT || join(dirname(fileURLToPath(import.meta.url)), "../../../server/src/game-data/anticheat/buildingProps.json");
const token = (await (await fetch(`${server}api/v1.7.3-beta/player/getinfo`, { method: "POST", headers: { "Content-Type": "application/x-www-form-urlencoded" }, body: `version=128&email=${encodeURIComponent(process.env.EMAIL)}&password=${encodeURIComponent(process.env.PASSWORD)}` })).json()).token;
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
try {
  const page = await browser.newPage();
  await page.goto(`${server}?token=${token}&language=english&shell=0`);
  await page.waitForFunction(() => window.__game && window.__game.GLOBAL._loadmode === "build", null, { timeout: 90000 });
  await page.waitForTimeout(3000);
  const data = await page.evaluate(() => {
    const G = window.__game.GLOBAL;
    const P = window.__classByName("INFERNOYARDPROPS");
    const num = (v) => (v && typeof v.Get === "function" ? v.Get() : Number(v));
    const table = (rows, withCosts = false) => {
      const t = {};
      rows.forEach((p, i) => {
        if (!p) return;
        const id = Number(p.id ?? i + 1);
        const e = { name: String(p.name ?? ""), type: String(p.type ?? ""), levels: Array.isArray(p.costs) ? p.costs.length : 0 };
        if (Array.isArray(p.capacity)) e.capacity = p.capacity.map(num);
        if (Array.isArray(p.quantity)) e.quantity = p.quantity.map(num);
        // (12 November: only where it is offered, can_fortify: the server caps a save's `fort` at this)
        if (p.can_fortify === true && Array.isArray(p.fortify_costs)) e.fortify = p.fortify_costs.length;
        if (Array.isArray(p.produce)) e.produce = true;
        // (18 October: what each level costs to build or upgrade, [r1, r2, r3], for the server's kit price floor)
        if (withCosts && Array.isArray(p.costs)) e.costs = p.costs.map((c) => [num(c?.r1) || 0, num(c?.r2) || 0, num(c?.r3) || 0]);
        // (12 November: and what each level of calcification costs, for a kit with calcified buildings)
        if (withCosts && p.can_fortify === true && Array.isArray(p.fortify_costs)) e.fortifyCosts = p.fortify_costs.map((c) => [num(c?.r1) || 0, num(c?.r2) || 0, num(c?.r3) || 0]);
        t[id] = e;
      });
      return t;
    };
    G.SetBuildingProps();
    return {
      main: table(P._infernoYardProps),
      outpost: table(G.outpostPropsTable, true),
      outpostCapacity: Number(G._outpostCapacity && G._outpostCapacity.Get ? G._outpostCapacity.Get() : 0),
    };
  });
  const result = { note: "Generated by client-web/tools/anticheat/dump-building-props.mjs from the running game. Do not edit.", generated: new Date().toISOString(), ...data };
  writeFileSync(out, JSON.stringify(result, null, 1) + "\n");
  console.log(`main: ${Object.keys(data.main).length} building types, outpost: ${Object.keys(data.outpost).length}; outpost capacity ${data.outpostCapacity} -> ${out}`);
} finally {
  await browser.close();
}
